const { chromium } = require('playwright');
const path = require('path');
const http = require('http'); const fs = require('fs');
const root = path.resolve(__dirname, '../..');
const srv = http.createServer((q, s) => { const f = path.join(root, decodeURIComponent(q.url.split('?')[0]) === '/' ? 'index.html' : q.url.split('?')[0]); fs.readFile(f, (e, d) => { if (e) { s.writeHead(404); s.end(); } else { s.writeHead(200, {'Content-Type': f.endsWith('.html') ? 'text/html' : 'application/octet-stream'}); s.end(d); } }); }).listen(5791);
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errs=[]; p.on('pageerror', e => errs.push(e.message));
  await p.goto('http://localhost:5791/?demo');
  const out = n => path.join(__dirname, 'shots', n + '.png');
  await p.screenshot({ path: out('1-start') });
  await p.click('#connectBtn'); await p.waitForTimeout(500);
  await p.click('text=Highway'); await p.waitForTimeout(1500);
  await p.screenshot({ path: out('2-live') });
  await p.evaluate(() => document.querySelector('#bus').closest('.card').scrollIntoView());
  await p.waitForTimeout(200); await p.screenshot({ path: out('3-vehicle') });
  await p.click('#setDtc'); await p.waitForTimeout(400);
  await p.evaluate(() => document.querySelector('#dtc').closest('.card').scrollIntoView());
  await p.waitForTimeout(200); await p.screenshot({ path: out('4-codes') });
  await p.fill('#raw', 'ATGET VIN'); await p.press('#raw', 'Enter'); await p.waitForTimeout(400);
  await p.evaluate(() => document.querySelector('#log').closest('.card').scrollIntoView());
  await p.waitForTimeout(200); await p.screenshot({ path: out('5-console') });
  await p.setViewportSize({ width: 1200, height: 860 }); await p.evaluate(()=>scrollTo(0,0));
  await p.click('#driveSim'); await p.waitForTimeout(3000);
  await p.screenshot({ path: out('6-desktop') });
  console.log('errors:', errs);
  await b.close(); srv.close();
})();
